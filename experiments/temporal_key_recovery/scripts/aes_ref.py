RCON = [1, 2, 4, 8, 0x10, 0x20, 0x40, 0x80, 0x1b, 0x36]

def xtime(x: int) -> int:
    return ((x << 1) ^ (0x1b if (x & 0x80) else 0)) & 0xff

def ark_concrete(s: bytearray, k: bytes) -> None:
    for i in range(16):
        s[i] ^= k[i]

def sb_concrete(s: bytearray) -> bytearray:
    return bytearray([SBOX[b] for b in s])

def sr_concrete(s: bytearray) -> bytearray:
    out = bytearray(16)
    for r in range(4):
        for c in range(4):
            out[4 * c + r] = s[4 * ((c + r) % 4) + r]
    return out

def mc_concrete(s: bytearray) -> bytearray:
    out = bytearray(s)
    for c in range(4):
        o = 4 * c
        t = s[o] ^ s[o + 1] ^ s[o + 2] ^ s[o + 3]
        out[o] = s[o] ^ t ^ xtime(s[o] ^ s[o + 1])
        out[o + 1] = s[o + 1] ^ t ^ xtime(s[o + 1] ^ s[o + 2])
        out[o + 2] = s[o + 2] ^ t ^ xtime(s[o + 2] ^ s[o + 3])
        out[o + 3] = s[o + 3] ^ t ^ xtime(s[o + 3] ^ s[o])
    return out

def expand_key(key: bytes) -> list[bytes]:
    ks = [bytes(key)]
    for n in range(1, 11):
        p = ks[n - 1]
        t = [
            SBOX[p[13]] ^ RCON[n - 1],
            SBOX[p[14]],
            SBOX[p[15]],
            SBOX[p[12]]
        ]
        q = bytearray(16)
        for r in range(4):
            q[r] = p[r] ^ t[r]
        for c in range(1, 4):
            for r in range(4):
                i = 4 * c + r
                q[i] = p[i] ^ q[i - 4]
        ks.append(bytes(q))
    return ks

def encrypt_with_trace(plaintext: bytes, key: bytes) -> dict:
    if len(plaintext) != 16 or len(key) != 16:
        raise ValueError("plaintext and AES-128 key must be 16 bytes")
    keys = expand_key(key)
    state = bytearray(plaintext)
    ark_concrete(state, keys[0])
    rounds = {}
    for rnd in range(1, 11):
        sb = sb_concrete(state)
        sr = sr_concrete(sb)
        mc = mc_concrete(sr) if rnd < 10 else bytearray(sr)
        ark = bytearray(mc)
        ark_concrete(ark, keys[rnd])
        rounds[rnd] = {"SB": bytes(sb), "SR": bytes(sr), "MC": bytes(mc), "ARK": bytes(ark)}
        state = ark
    return {"rounds": rounds, "ciphertext": bytes(state)}

def observe_state(P: bytes, K: bytes, round: int, stage: str, bit_index: int) -> int:
    if stage not in {"SB", "SR", "MC", "ARK"}:
        raise ValueError(f"invalid stage: {stage}")
    if not 1 <= round <= 10 or not 0 <= bit_index < 128:
        raise ValueError("round or bit_index out of range")
    state = encrypt_with_trace(P, K)["rounds"][round][stage]
    return (state[bit_index // 8] >> (bit_index % 8)) & 1
